/**
 * Provider routing for private, OpenAI-compatible deployments.
 *
 * A company deployment adds one `llm-pi-ai` route that speaks Chat Completions
 * at the configured base URL and lists the single model that endpoint serves,
 * with the deployment's declared capacity, and pins that model as the agent
 * default. Until `dsh.llmModel` names that model, the route lists and pins an
 * unconfigured placeholder so the application can boot for discovery. The
 * endpoint, its model id, its credential reference, and the default
 * model are deployment-owned; because this overlay sits above the profile, a
 * Models-page edit to them is refused by the configuration editor. The same
 * overlay names that route to the Models page, so only it renders read-only and
 * user-added routes keep their own profiles. The DeepSeek mode generates no
 * overlay, so it owns no route.
 * @module @deepseek-ai/dsh-vscode/host/provider
 */
import { companyBaseUrlError, UNCONFIGURED_MODEL_ID, type ProviderSettings } from './settings.ts'

/** Route name grammar: a lowercase hyphenated identifier. */
const ROUTE = /^[a-z][a-z0-9-]*$/u

/** The module one overlay inserts to refuse placeholder inference, and the id it refuses. */
export interface ProviderGate {
  /** Absolute file URL of the generated gate module. */
  readonly module: string
  /** Model id the gate refuses. */
  readonly model: string
}

/**
 * Build the overlay that adds the private route.
 *
 * A deployment with an endpoint but no model yet boots on
 * {@link UNCONFIGURED_MODEL_ID}: the overlay names that placeholder in the
 * route's model list and in the agent default, so the agent composition
 * resolves while the endpoint's real model is still unknown. The Models page
 * discovers the endpoint's listing and saves the chosen id to `dsh.llmModel`;
 * the next launch generates this overlay with the real model. The placeholder
 * is not a model any endpoint serves, so it is not usable for inference: when a
 * gate module is supplied, the overlay inserts it to refuse that id instead of
 * sending it to the endpoint.
 * @param settings - provider configuration.
 * @param gate - the placeholder-inference gate to insert, when the caller wrote one.
 * @returns the patch document, or undefined for the DeepSeek route.
 * @throws when the route name, URL, credential name, or a model limit is unusable.
 */
export function providerPatch(settings: ProviderSettings, gate?: ProviderGate): string | undefined {
  if (settings.mode === 'deepseek') return undefined
  if (!ROUTE.test(settings.route)) {
    throw new Error(`dsh: provider route must be a lowercase hyphenated identifier, got ${JSON.stringify(settings.route)}`)
  }
  const urlError = companyBaseUrlError(settings.baseUrl)
  if (urlError !== undefined) throw new Error(`dsh: ${urlError}`)
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(settings.apiKeyEnv)) {
    throw new Error(`dsh: credential reference must be an environment name, got ${JSON.stringify(settings.apiKeyEnv)}`)
  }
  const placeholder = settings.model.trim() === ''
  const model = placeholder ? UNCONFIGURED_MODEL_ID : settings.model
  const contextWindow = deploymentLimit(settings.contextWindow, 'context window')
  const maxTokens = deploymentLimit(settings.maxTokens, 'output-token cap')
  return [
    '# Generated by the DSH extension: private OpenAI-compatible provider route.',
    '# Deployment-owned: the endpoint, the model it serves, and their limits.',
    '# The agent default pins that model; a profile edit to it is refused.',
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    `      ${settings.route}:`,
    '        api: openai-completions',
    `        baseURL: ${quote(settings.baseUrl)}`,
    `        apiKeyEnv: ${quote(settings.apiKeyEnv)}`,
    '        models:',
    ...placeholder
      ? [
          '          # Placeholder until dsh.llmModel names the model this endpoint serves.',
          '          # The application boots and the Models page can run discovery; this id',
          '          # is not served by the endpoint and is not usable for inference.',
        ]
      : [],
    `          - id: ${quote(model)}`,
    ...contextWindow === undefined ? [] : [`            contextWindow: ${String(contextWindow)}`],
    ...maxTokens === undefined ? [] : [`            maxTokens: ${String(maxTokens)}`],
    '# Keeps a fresh profile on the company route instead of the composition',
    '# default (deepseek-official/deepseek-flash).',
    '- id: agent-default-model',
    '  config:',
    `    provider: ${quote(settings.route)}`,
    `    model: ${quote(model)}`,
    '# Only this route is deployment-owned on the Models page. The row config is',
    '# restated whole because a patch replaces the config the shipped overlay set.',
    '- id: ui-settings-models',
    '  config:',
    '    credentialOnboarding: false',
    `    deploymentOwnedRoute: ${quote(settings.route)}`,
    // A new row needs an explicit `insert:` list: a bare row would only patch an existing entry with that id.
    ...gate === undefined || !placeholder
      ? []
      : [
          '# The deployment has no model yet: refuse inference for the placeholder instead of',
          '# sending an id no endpoint serves.',
          '- insert:',
          '    - id: company-unconfigured-model-gate',
          `      name: ${quote(gate.module)}`,
          '      config:',
          `        model: ${quote(gate.model)}`,
        ],
    '',
  ].join('\n')
}

/**
 * Validate one optional model limit.
 * @param value - configured positive integer; undefined leaves the adapter default.
 * @param label - name used in the error.
 * @returns the value, or undefined when the deployment sets none.
 * @throws when a configured value is not a positive integer.
 */
function deploymentLimit(value: number | undefined, label: string): number | undefined {
  if (value === undefined) return undefined
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`dsh: provider model ${label} must be a positive integer, got ${JSON.stringify(value)}`)
  }
  return value
}

/**
 * Quote one YAML scalar.
 * @param value - scalar text.
 * @returns the value as a printable YAML string.
 */
function quote(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}
