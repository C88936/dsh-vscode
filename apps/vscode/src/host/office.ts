/**
 * Bundled Office composition for the VS Code runtime.
 *
 * The Web profile mounts no Office skill provider, and the terminal and editor
 * adapters are mounted as generated rows. Office follows the same pattern: the
 * companion resolves the bundled skill package, the LibreOffice Kit CLI, and an
 * absolute Node executable from the installation it boots, then writes one
 * overlay that mounts the skills. A launch that carries the offline authoring
 * payload also mounts `load_workspace_dependencies`; without it, authoring has
 * no interpreter while rendering and export still work.
 * @module @deepseek-ai/dsh-vscode/host/office
 */
import { createRequire } from 'node:module'
import { readFileSync, statSync } from 'node:fs'
import { dirname, isAbsolute, join, relative, sep } from 'node:path'

/** Inputs for one Office composition. */
export interface OfficeCompositionInput {
  /** Absolute installation manifest the profile boots from. */
  readonly installAnchor: string
  /** Absolute Node executable the companion runs, passed to the skill config. */
  readonly node: string
  /** Runtime directory that may carry `primary-runtime/`; defaults to the installation root. */
  readonly runtimeRoot?: string
}

/** Outcome of resolving the Office composition. */
export type OfficeComposition =
  | {
    /** The overlay content to write, without a trailing newline. */
    readonly patch: string
    /** User-facing facts about what was mounted. */
    readonly detail: string
  }
  | {
    /** Why Office skills are not mountable in this launch. */
    readonly reason: string
  }

/**
 * Resolve the bundled Office skill package, its LibreOffice Kit CLI, and the
 * optional authoring payload.
 * @param input - installation anchor, companion Node executable, and runtime root.
 * @returns the generated overlay, or why Office skills cannot mount.
 */
export function officeComposition(input: OfficeCompositionInput): OfficeComposition {
  const runtimeRoot = input.runtimeRoot ?? dirname(input.installAnchor)
  const skillPackage = resolvePackage(input.installAnchor, '@deepseek-ai/dsh-skill-office')
  if (skillPackage.ok === false) return skillPackage
  const kitPackage = resolvePackage(input.installAnchor, '@deepseek-ai/libreoffice-kit')
  if (kitPackage.ok === false) return kitPackage
  const assetRoot = join(skillPackage.directory, 'assets')
  const cli = join(kitPackage.directory, 'lib', 'cli.js')
  if (!isDirectory(assetRoot)) return { reason: `the bundled Office assets are missing at ${assetRoot}` }
  if (!isFile(cli)) return { reason: `the LibreOffice Kit CLI is missing at ${cli}` }
  if (!isFile(input.node)) return { reason: `the Office skill needs an absolute Node executable, received ${input.node}` }

  const payload = authoringPayload(runtimeRoot)
  const rows = [
    '    - id: skill-office',
    "      name: '@deepseek-ai/dsh-skill-office'",
    '      config:',
    `        assetRoot: ${quote(assetRoot)}`,
    `        node: ${quote(input.node)}`,
    `        cli: ${quote(cli)}`,
  ]
  if (payload.ok) {
    rows.push(
      '    - id: workspace-dependencies',
      "      name: '@deepseek-ai/dsh-tool-workspace-dependencies'",
      '      config:',
      `        source: ${quote(payload.directory)}`,
    )
  }
  return {
    patch: [
      '# Generated by the DSH VS Code extension: mount the bundled Office skills.',
      '- insert:',
      ...rows,
      '',
    ].join('\n'),
    detail: payload.ok
      ? `Office skills mounted with the bundled authoring payload at ${payload.directory}`
      : `Office skills mounted; document authoring needs a primary runtime payload (${payload.reason})`,
  }
}

/**
 * Find the offline Python and Node payload that Office authoring uses.
 * @param runtimeRoot - runtime directory that may contain `primary-runtime/`.
 * @returns the payload directory, or why it is unusable.
 */
function authoringPayload(runtimeRoot: string): { ok: true; directory: string } | { ok: false; reason: string } {
  const directory = join(runtimeRoot, 'primary-runtime')
  const manifest = join(directory, 'runtime.json')
  if (!isFile(manifest)) return { ok: false, reason: `no runtime.json below ${directory}` }
  try {
    const parsed = JSON.parse(readFileSync(manifest, 'utf8')) as { platform?: unknown; arch?: unknown }
    if (parsed.platform !== process.platform || parsed.arch !== process.arch) {
      return { ok: false, reason: `${manifest} targets ${String(parsed.platform)}-${String(parsed.arch)}` }
    }
    return { ok: true, directory }
  } catch (error) {
    return { ok: false, reason: `${manifest} is unreadable: ${error instanceof Error ? error.message : String(error)}` }
  }
}

/**
 * Resolve one installed package directory from the installation that boots the profile.
 *
 * The package must belong to that installation: a copy resolvable from an
 * ancestor `node_modules`, a global directory, or a development checkout is not
 * the one this profile boots, so mounting it would name files the packaged
 * runtime does not serve.
 * @param anchor - absolute installation `package.json`.
 * @param name - npm package name.
 * @returns the package directory, or why it cannot be resolved.
 */
function resolvePackage(anchor: string, name: string): { ok: true; directory: string } | { ok: false; reason: string } {
  try {
    const manifest = createRequire(anchor).resolve(`${name}/package.json`)
    const directory = dirname(manifest)
    if (!isInside(dirname(anchor), directory)) {
      return {
        ok: false,
        reason: `${name} is not installed for ${anchor}: it resolves outside the installation at ${directory}`,
      }
    }
    return { ok: true, directory }
  } catch (error) {
    return {
      ok: false,
      reason: `${name} is not installed for ${anchor}: ${error instanceof Error ? error.message : String(error)}`,
    }
  }
}

/**
 * @param root - installation directory.
 * @param target - resolved path.
 * @returns whether the path is the installation directory or below it.
 */
function isInside(root: string, target: string): boolean {
  const path = relative(root, target)
  return path === '' || path !== '..' && !path.startsWith(`..${sep}`) && !isAbsolute(path)
}

/**
 * @param value - path or identifier. @returns a YAML double-quoted scalar.
 */
function quote(value: string): string {
  return JSON.stringify(value)
}

/** @param path - candidate. @returns whether it is a regular file. */
function isFile(path: string): boolean {
  try {
    return statSync(path).isFile()
  } catch {
    return false
  }
}

/** @param path - candidate. @returns whether it is a directory. */
function isDirectory(path: string): boolean {
  try {
    return statSync(path).isDirectory()
  } catch {
    return false
  }
}
