/**
 * Local plugin sources for private networks.
 *
 * A LAN deployment cannot reach a public registry or Git host, so plugins are
 * prepared module sources (a package directory or one entry module file) copied
 * into the network. The extension turns a list of local paths into an overlay
 * that inserts each one as a Loader row, which is the same mechanism a profile
 * patch uses for any out-of-tree plugin. Package archives are not module
 * sources; they are refused here and installed as bundles from the Plugins page.
 * @module @deepseek-ai/dsh-vscode/host/plugins
 */
import { existsSync, readFileSync, statSync } from 'node:fs'
import { basename, isAbsolute, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

/** One local plugin to mount. */
export interface LocalPlugin {
  /** Row id inside the composition. */
  readonly id: string
  /** Absolute directory or module path inside the private network. */
  readonly path: string
}

/** Row id grammar: lowercase letters, digits, dot and hyphen. */
const ID = /^[a-z][a-z0-9.-]*$/u

/** File names this adapter refuses because a bundle installer owns archives. */
const ARCHIVE = /\.(?:tgz|tar\.gz|tar|zip)$/iu

/** Package.json fields this adapter reads for the root entry. */
interface PackageManifest {
  readonly main?: unknown
  readonly module?: unknown
  readonly exports?: unknown
}

/**
 * Build the overlay that mounts local plugins.
 * @param plugins - configured plugins.
 * @returns the patch document, or undefined when none are configured.
 * @throws when an id or path is unusable.
 */
export function pluginsPatch(plugins: readonly LocalPlugin[]): string | undefined {
  if (plugins.length === 0) return undefined
  const seen = new Set<string>()
  const rows: string[] = []
  for (const plugin of plugins) {
    if (!ID.test(plugin.id)) {
      throw new Error(`dsh: local plugin id must be a lowercase identifier, got ${JSON.stringify(plugin.id)}`)
    }
    if (seen.has(plugin.id)) throw new Error(`dsh: duplicate local plugin id ${JSON.stringify(plugin.id)}`)
    seen.add(plugin.id)
    if (plugin.path.trim() === '') throw new Error(`dsh: local plugin ${plugin.id} has no path`)
    rows.push(`    - id: ${plugin.id}`, `      name: ${quote(pluginEntry(plugin.path))}`)
  }
  return [
    '# Generated by the DSH extension: local plugin rows for a private network.',
    '- insert:',
    ...rows,
    '',
  ].join('\n')
}

/**
 * Resolve a configured plug-in file or package directory to a Loader ESM URL.
 * @param configured - absolute path, file URL, or directory containing package.json.
 * @returns a file URL naming the plug-in entry module.
 * @throws when the path is an archive or does not identify an existing entry module.
 */
export function pluginEntry(configured: string): string {
  const path = configured.startsWith('file:') ? fileURLToPath(configured) : configured
  if (!isAbsolute(path)) throw new Error(`dsh: local plugin path must be absolute: ${configured}`)
  const target = resolve(path)
  if (!existsSync(target)) throw new Error(`dsh: local plugin path does not exist: ${target}`)
  if (statSync(target).isFile()) {
    if (ARCHIVE.test(basename(target))) {
      throw new Error(
        `dsh: local plugin path is an archive, not a module: ${target}. Install the package as a bundle from the Plugins page.`,
      )
    }
    return pathToFileURL(target).href
  }
  const manifestPath = join(target, 'package.json')
  if (!existsSync(manifestPath)) throw new Error(`dsh: local plugin directory has no package.json: ${target}`)
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as PackageManifest
  const entry = packageEntry(target, manifest)
  const resolved = resolve(target, entry)
  if (!existsSync(resolved) || !statSync(resolved).isFile()) {
    throw new Error(`dsh: local plugin entry does not exist or is not a file: ${resolved}`)
  }
  return pathToFileURL(resolved).href
}

/**
 * Resolve the ESM entry a package manifest declares for the import condition.
 *
 * `exports` wins when present; otherwise `module`, then `main`, name the entry
 * for packages that declare no exports map. There is no index.js fallback: a
 * missing or unsupported entry is an error.
 *
 * Exports targets follow Node's package exports rules for the subset this
 * adapter supports, which is necessary because Node's resolver cannot be reused
 * here: `import.meta.resolve` resolves installed package specifiers only, and
 * no maintained exports resolver is a dependency of this application. Active
 * condition keys are tried in declaration order. An array tries each target,
 * continuing only past invalid targets and targets that no active condition
 * matches; a resolved path whose file is missing stays an error. An explicit
 * `null` target is a refusal, not a miss, so it never falls through to an
 * unrelated entry. A target that is not a string, array, object, or null, or a
 * string that is not a `"./"` path, is invalid.
 * @param target - absolute package directory, named in errors.
 * @param manifest - decoded package.json fields.
 * @returns the entry path relative to the package directory.
 * @throws when the manifest declares no usable root entry or an invalid target.
 */
function packageEntry(target: string, manifest: PackageManifest): string {
  if (manifest.exports !== undefined) {
    const result = exportsResult(manifest.exports, target)
    if (result.kind === 'entry') return result.entry
    if (result.kind === 'refused') {
      throw new Error(
        `dsh: local plugin package ${target} refuses the import condition with an explicit null exports target; declare exports["."] with an import, node, or default target, or remove "exports" to use module or main`,
      )
    }
    throw new Error(
      `dsh: local plugin package ${target} exports no root module for the import condition; declare exports["."] with an import, node, or default target, or remove "exports" to use module or main`,
    )
  }
  const entry = stringEntry(manifest.module) ?? stringEntry(manifest.main)
  if (entry === undefined) {
    throw new Error(
      `dsh: local plugin package ${target} declares no module entry; set exports["."] for the import condition, module, or main in package.json`,
    )
  }
  return entry
}

/** Conditions this adapter resolves an ESM root entry under. */
const IMPORT_CONDITIONS: ReadonlySet<string> = new Set(['import', 'node', 'default'])

/**
 * Resolve one `exports` target under the supported import conditions.
 *
 * `condition-miss` lets an enclosing condition object or array try its next
 * candidate. `refused` is an explicit `null`, which Node reports as "not
 * exported": resolution stops instead of falling through. Invalid targets
 * throw, so callers can report them rather than retrying another candidate.
 */
type TargetResult =
  | { readonly kind: 'entry'; readonly entry: string }
  | { readonly kind: 'condition-miss' }
  | { readonly kind: 'refused' }

/** A package `exports` target that Node's ESM resolver rejects. */
class InvalidExportTarget extends Error {
  /**
   * @param target - rejected target value rendered for the report.
   */
  constructor(readonly target: string) {
    super(`invalid package export target ${target}`)
    this.name = 'InvalidExportTarget'
  }
}

/**
 * Resolve the root ESM entry from a package `exports` value.
 * @param exports - decoded `exports` value.
 * @param packageTarget - package directory, named in invalid-target errors.
 * @returns the resolution outcome.
 * @throws when the value contains an invalid target.
 */
function exportsResult(exports: unknown, packageTarget: string): TargetResult {
  try {
    if (typeof exports === 'string') return stringTarget(exports)
    if (Array.isArray(exports)) return arrayTarget(exports)
    if (exports === null) return { kind: 'refused' }
    if (typeof exports !== 'object') throw new InvalidExportTarget(describeTarget(exports))
    const map = exports as Record<string, unknown>
    if (Object.keys(map).some(key => key.startsWith('.'))) {
      return '.' in map ? targetEntry(map['.']) : { kind: 'condition-miss' }
    }
    return conditionTarget(map)
  } catch (error) {
    if (!(error instanceof InvalidExportTarget)) throw error
    throw new Error(
      `dsh: local plugin package ${packageTarget} declares an invalid exports target ${error.target}; exports targets must be "./" paths, arrays, condition maps, or null`,
    )
  }
}

/**
 * Resolve one target value, dispatching on its type.
 * @param target - decoded target value.
 * @returns the resolution outcome.
 * @throws when the value is an invalid target.
 */
function targetEntry(target: unknown): TargetResult {
  if (typeof target === 'string') return stringTarget(target)
  if (Array.isArray(target)) return arrayTarget(target)
  if (target === null) return { kind: 'refused' }
  if (typeof target !== 'object') throw new InvalidExportTarget(describeTarget(target))
  return conditionTarget(target as Record<string, unknown>)
}

/**
 * Try a condition object's active keys in declaration order.
 * @param map - condition map.
 * @returns the first non-miss resolution, or `condition-miss` when none applies.
 */
function conditionTarget(map: Record<string, unknown>): TargetResult {
  for (const [condition, value] of Object.entries(map)) {
    if (!IMPORT_CONDITIONS.has(condition)) continue
    const result = targetEntry(value)
    if (result.kind === 'condition-miss') continue
    return result
  }
  return { kind: 'condition-miss' }
}

/**
 * Try array targets in order, continuing past invalid and unmatched targets.
 *
 * A resolved target is returned immediately, so a later file is not tried when
 * the resolved file is missing. The last invalid target or explicit null among
 * the candidates decides the result; an empty array refuses, as in Node.
 * @param targets - array target values.
 * @returns the resolution outcome.
 * @throws when the last decisive candidate was an invalid target.
 */
function arrayTarget(targets: readonly unknown[]): TargetResult {
  if (targets.length === 0) return { kind: 'refused' }
  let lastInvalid: InvalidExportTarget | undefined
  let lastRefused = false
  for (const candidate of targets) {
    let result: TargetResult
    try {
      result = targetEntry(candidate)
    } catch (error) {
      if (!(error instanceof InvalidExportTarget)) throw error
      lastInvalid = error
      lastRefused = false
      continue
    }
    if (result.kind === 'entry') return result
    if (result.kind === 'refused') {
      lastInvalid = undefined
      lastRefused = true
    }
  }
  if (lastInvalid !== undefined) throw lastInvalid
  return lastRefused ? { kind: 'refused' } : { kind: 'condition-miss' }
}

/**
 * Validate a string target as a relative `"./"` module path.
 * @param value - string target.
 * @returns the entry path.
 * @throws when the value is not a relative path or contains an invalid segment.
 */
function stringTarget(value: string): TargetResult {
  if (!value.startsWith('./')) throw new InvalidExportTarget(JSON.stringify(value))
  const segments = value.slice(2).split(/[\\/]/u)
  if (segments.some(segment =>
    segment === '' || segment === '.' || segment === '..' || segment.toLowerCase() === 'node_modules')) {
    throw new InvalidExportTarget(JSON.stringify(value))
  }
  return { kind: 'entry', entry: value }
}

/**
 * @param target - rejected target value.
 * @returns the value rendered for an error message.
 */
function describeTarget(target: unknown): string {
  return typeof target === 'string' ? JSON.stringify(target) : String(target)
}

/**
 * @param value - candidate module path.
 * @returns the path when it is non-empty.
 */
function stringEntry(value: unknown): string | undefined {
  return typeof value === 'string' && value !== '' ? value : undefined
}

/**
 * Quote one YAML scalar.
 * @param value - scalar text.
 * @returns the value as a printable YAML string.
 */
function quote(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}
